int CLuaInstance::RenderString(lua_State *L)
{
	int x, y, w, boxh, center;
	Font *font = NULL;
	lua_Unsigned c;
	const char *text;
	int numargs = lua_gettop(L);
	LUA_DEBUG("CLuaInstance::%s %d\n", __func__, numargs);
	c = COL_MENUCONTENT_TEXT;
	w = 0;
	boxh = 0;
	center = 0;

	CLuaData *W = CheckData(L, 1);
	if (!W || !W->fbwin)
		return 0;

	int step = 0;
	bool isDynFont = false;
	if (lua_isboolean(L, 2))
	{
		if (lua_toboolean(L, 2) == true)
			isDynFont = true;
		step = 1;
	}

	bool found = true;
	font = ScriptNeutrino::FontOf(W->fontmap, luaL_checkint(L, 2 + step), isDynFont, found);
	if (!found)
	{
		lua_pushinteger(L, 0); /* no font found */
		return 1;
	}

	text = luaL_checkstring(L, 3 + step);	/* text */
	x = luaL_checkint(L, 4 + step);
	y = luaL_checkint(L, 5 + step);
	if (numargs > 5 + step)
		c = luaL_checkunsigned(L, 6 + step);
	bool sized = false;
	if (numargs > 6 + step)
	{
		w = luaL_checkint(L, 7 + step);
		sized = true;
	}
	if (numargs > 7 + step)
		boxh = luaL_checkint(L, 8 + step);
	if (numargs > 8 + step)
		center = luaL_checkint(L, 9 + step);

	ScriptNeutrino::RenderText params;
	params.x = x;
	params.y = y;
	params.w = w;
	params.boxh = boxh;
	params.center = center;
	params.color = c;
	params.sized = sized;

	lua_pushinteger(L, ScriptNeutrino::RenderString(W->fbwin, font, text, params));
	return 1;
}

