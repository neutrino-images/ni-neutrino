CLuaInstance::CLuaInstance()
{
	DisableAbort = true;
	/* Create the intepreter object. */
	lua = luaL_newstate();

	/* register standard + custom functions. */
	LuaInstRegisterFunctions(lua);
}

CLuaInstance::~CLuaInstance()
{
	if (lua != NULL)
	{
		lua_close(lua);
		lua = NULL;
	}
}

