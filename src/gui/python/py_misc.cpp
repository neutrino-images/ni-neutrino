/* M.runScript(script, *args): runs another script, with what follows the
 * name handed to it, as the Lua binding hands its arguments on. */
PyObject *CPythonInstMisc::runScript(PyObject *self, PyObject *args, PyObject *kwds)
{
	static const char *kwlist[] = { "script", NULL };
	const char *script = NULL;

	if (!PyArg_ParseTupleAndKeywords(args, kwds, "s", (char **)kwlist, &script))
		return NULL;

	std::vector<std::string> script_args;
	Py_ssize_t count = (args != NULL) ? PyTuple_GET_SIZE(args) : 0;
	for (Py_ssize_t i = 1; i < count; i++)
	{
		PyObject *str = PyObject_Str(PyTuple_GET_ITEM(args, i));
		if (str == NULL)
		{
			PyErr_Clear();
			continue;
		}
		const char *s = PyUnicode_AsUTF8(str);
		if (s != NULL)
		{
			if (s[0] != '\0')
				script_args.push_back(s);
		}
		else
			PyErr_Clear();
		Py_DECREF(str);
	}

	CPythonInstance *python = new CPythonInstance();
	python->runScript(script, &script_args);
	script_args.clear();
	delete python;

	Py_RETURN_NONE;
}

/* Answers the revision and the hardware, as the Lua binding answers with
 * two values. */
PyObject *CPythonInstMisc::GetRevision(PyObject *self, PyObject *args, PyObject *kwds)
{
	unsigned int rev = 0;
	std::string hw = "";
#if HAVE_CST_HARDWARE
	hw = "Coolstream";
#else
	hw = g_info.hw_caps->boxvendor;
	hw += "_";
	hw += g_info.hw_caps->boxname;
#endif
	rev = cs_get_revision();
	return Py_BuildValue("(is)", (int)rev, hw.c_str());
}

PyObject *CPythonInstMisc::checkVersion(PyObject *self, PyObject *args, PyObject *kwds)
{
	static const char *kwlist[] = { "major", "minor", NULL };
	int major = 0;
	int minor = 0;

	if (!PyArg_ParseTupleAndKeywords(args, kwds, "ii", (char **)kwlist, &major, &minor))
		return NULL;

	if ((major > PYTHON_API_VERSION_MAJOR) ||
	    ((major == PYTHON_API_VERSION_MAJOR) && (minor > PYTHON_API_VERSION_MINOR)))
	{
		char msg[1024];
		snprintf(msg, sizeof(msg) - 1, "%s (v%d.%d)\n%s v%d.%d",
			g_Locale->getText(LOCALE_LUA_VERSIONSCHECK1),
			PYTHON_API_VERSION_MAJOR, PYTHON_API_VERSION_MINOR,
			g_Locale->getText(LOCALE_LUA_VERSIONSCHECK2),
			major, minor);
		DisplayErrorMessage(msg, "Python Script Error:");
	}

	return PyBool_FromLong(1); /* for backward compatibility */
}

PyObject *CPythonInstMisc::postMsg(PyObject *self, PyObject *args, PyObject *kwds)
{
	static const char *kwlist[] = { "msg", NULL };
	int msg = 0;
	neutrino_msg_t post_msg = 0;

	if (!PyArg_ParseTupleAndKeywords(args, kwds, "i", (char **)kwlist, &msg))
		return NULL;

	switch (msg)
	{
		case POSTMSG_STANDBY_ON:
			post_msg = NeutrinoMessages::STANDBY_ON;
			break;
		default:
			Py_RETURN_NONE;
	}

	g_RCInput->postMsg(post_msg, 0);
	Py_RETURN_NONE;
}

PyObject *CPythonInstMisc::getTimeOfDay(PyObject *self, PyObject *args, PyObject *kwds)
{
	struct timeval t1;
	gettimeofday(&t1, NULL);
	double dt = (double)t1.tv_sec + ((double)t1.tv_usec) / 1000000ULL;

	return PyFloat_FromDouble(dt);
}

